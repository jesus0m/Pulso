#!/usr/bin/env python3
"""Generates Android string resources from the iOS string catalog (App/Localizable.xcstrings).

Spanish is the source language of the catalog. Resource names are a deterministic slug of the
Spanish source text so the Android app shows exactly the same copy as iOS.
Usage (from repo root): python3 android/scripts/generate_strings.py
"""
import json, re, unicodedata, pathlib
from xml.sax.saxutils import escape

root = pathlib.Path(__file__).resolve().parents[2]
catalog = json.loads((root / "App/Localizable.xcstrings").read_text(encoding="utf-8"))

def slug(text):
    t = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    t = re.sub(r"%[@lds0-9$.]+", " ", t)
    t = re.sub(r"[^a-zA-Z0-9]+", "_", t).strip("_").lower()
    t = t[:44].rstrip("_") or "s"
    return "s_" + t

def convert(text, has_args):
    """Swift format specifiers -> Android (positional so argument order can differ per language).

    Single left-to-right pass: `%%` stays an escaped percent, specifiers become positional,
    and a stray `%` is escaped when the string is used as a format string.
    """
    count = 0
    def repl(m):
        nonlocal count
        token = m.group(0)
        if token == "%%":
            return "%%" if has_args else "%"
        if m.group(2) is None:  # lone percent sign
            return "%%" if has_args else "%"
        if m.group(1):
            n = int(m.group(1)[:-1])
        else:
            count += 1
            n = count
        return f"%{n}${'d' if m.group(2) in ('lld', 'd', 'ld', 'lu') else 's'}"
    return re.sub(r"%%|%(\d+\$)?(@|lld|ld|lu|d|s)|%", repl, text)

def android_escape(text):
    out = escape(text).replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if out.startswith(("@", "?")):
        out = "\\" + out
    return out

names, used = {}, set()
for key in catalog["strings"]:
    n = slug(key)
    base, i = n, 2
    while n in used:
        n = f"{base}_{i}"; i += 1
    used.add(n); names[key] = n

def write(folder, lang):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by android/scripts/generate_strings.py from App/Localizable.xcstrings. Do not edit. -->",
             "<resources>"]
    for key, entry in catalog["strings"].items():
        if lang == "es":
            value = key
        else:
            unit = entry.get("localizations", {}).get(lang, {}).get("stringUnit", {})
            value = unit.get("value", key)
        has_args = bool(re.search(r"%(\d+\$)?(@|lld|ld|lu|d|s)", value))
        converted = convert(value, has_args)
        lines.append(f'    <string name="{names[key]}" formatted="{"true" if has_args else "false"}">{android_escape(converted)}</string>')
    lines.append("</resources>")
    out = root / "android/app/src/main/res" / folder
    out.mkdir(parents=True, exist_ok=True)
    (out / "strings_catalog.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")

write("values", "en")
write("values-es", "es")
(root / "android/scripts/string_names.txt").write_text(
    "\n".join(f"{v}\t{k}" for k, v in names.items()) + "\n", encoding="utf-8")
print(len(names), "strings")
